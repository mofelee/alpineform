#!/usr/bin/env bash

APF_INTEGRATION_ALPINE_ARCHITECTURE="x86_64"
APF_INTEGRATION_PLATFORM_ARCHITECTURE="amd64"
APF_INTEGRATION_ALPINE_BRANCH="${APF_INTEGRATION_ALPINE_BRANCH:-v3.24}"

case "$APF_INTEGRATION_ALPINE_BRANCH" in
  v3.21)
    APF_INTEGRATION_ALPINE_VERSION="3.21.7"
    APF_INTEGRATION_CLOUD_IMAGE_SHA512="612691a05c8ea3181b08d11a33572bc06ad3c2679760f6b20c5525dfcdf47f99f597ea485b3e7a4b533612aa283e52468c6b51a05a1e561c13b32ab59f6ec821"
    ;;
  v3.22)
    APF_INTEGRATION_ALPINE_VERSION="3.22.5"
    APF_INTEGRATION_CLOUD_IMAGE_SHA512="132c8f0f3926c2c63e389b251c144e173472049b39c2527e7b6bf3692bafdd17c09e6d2897f7cffcfaf9256ba2ca6de2545992ef2c0b9cca12e2548265954ab4"
    ;;
  v3.23)
    APF_INTEGRATION_ALPINE_VERSION="3.23.5"
    APF_INTEGRATION_CLOUD_IMAGE_SHA512="7f8818009bb80fb72c81e3dcb8a8aa4c55eda24606e571159e0c3ecaf521fd14d7fbdca06ce55f746db8c19a62302fbfda6b29fb6791619a21648edd5f340e31"
    ;;
  v3.24)
    APF_INTEGRATION_ALPINE_VERSION="3.24.1"
    APF_INTEGRATION_CLOUD_IMAGE_SHA512="ed976ef40de1f73adcb0a3b253ec9e73e43c408208fcc3c30dcdf7a69b91a387a4777f88c6b72345123edf3832d7cb49403ecce28ec84d496d4b3bad6fbd0923"
    ;;
  *)
    printf 'unsupported Alpine integration branch: %s (use v3.21, v3.22, v3.23, or v3.24)\n' \
      "$APF_INTEGRATION_ALPINE_BRANCH" >&2
    return 1 2>/dev/null || exit 1
    ;;
esac

APF_INTEGRATION_CLOUD_URL="https://dl-cdn.alpinelinux.org/alpine/$APF_INTEGRATION_ALPINE_BRANCH/releases/cloud"
APF_INTEGRATION_CLOUD_IMAGE="generic_alpine-${APF_INTEGRATION_ALPINE_VERSION}-x86_64-uefi-cloudinit-r0.qcow2"

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  printf 'version=%s\n' "$APF_INTEGRATION_ALPINE_VERSION"
  printf 'branch=%s\n' "$APF_INTEGRATION_ALPINE_BRANCH"
  printf 'architecture=%s\n' "$APF_INTEGRATION_ALPINE_ARCHITECTURE"
  printf 'platform_architecture=%s\n' "$APF_INTEGRATION_PLATFORM_ARCHITECTURE"
  printf 'cloud_url=%s\n' "$APF_INTEGRATION_CLOUD_URL"
  printf 'cloud_image=%s\n' "$APF_INTEGRATION_CLOUD_IMAGE"
  printf 'sha512=%s\n' "$APF_INTEGRATION_CLOUD_IMAGE_SHA512"
fi
